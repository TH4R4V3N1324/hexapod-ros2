#!/usr/bin/env python3
"""Generate the outdoor test worlds in hexapod_description/worlds.

    outdoor_slopes        hills at 5, 10, 15 and 20 deg (up, across the top, down) and side slopes
    outdoor_rocks         a seeded field of rocks and gentle bumps
    outdoor_low_friction  flat lanes from dry ground to wet tile, and a slippery slope

The robot walks along +x. Each lane sits at its own y, and scenario_runner.py spawns the robot at
the start of the lane it tests, so keep the two in step when changing a layout.

Usage: generate_outdoor_worlds.py [--seed N]
"""
import argparse
import math
import random
from pathlib import Path

WORLDS_DIR = Path(__file__).resolve().parent.parent / 'worlds'

# Rubber on dry earth. The feet are 1.5, and Gazebo's default engine (DART) uses the lower of the two
DRY_MU = 1.0

HEADER = '''<?xml version="1.0" ?>
<!-- Generated by scripts/generate_outdoor_worlds.py, edit that instead -->
<sdf version="1.9">
  <world name="{name}">

    <!-- Physics -->
    <physics name="1ms" type="bullet">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <!-- Required Harmonic system plugins -->
    <plugin filename="gz-sim-physics-system"
            name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system"
            name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system"
            name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-contact-system"
            name="gz::sim::systems::Contact"/>
    <plugin filename="gz-sim-sensors-system"
            name="gz::sim::systems::Sensors"/>
    <!-- IMU and magnetometer sensors only publish when their systems are loaded -->
    <plugin filename="gz-sim-imu-system"
            name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-magnetometer-system"
            name="gz::sim::systems::Magnetometer"/>

    <!-- Lighting -->
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          <material><ambient>0.35 0.4 0.3 1</ambient><diffuse>0.45 0.5 0.35 1</diffuse></material>
        </visual>
      </link>
    </model>
'''

FOOTER = '''
  </world>
</sdf>
'''

EARTH = (0.55, 0.45, 0.3)
ROCK = (0.5, 0.5, 0.48)


def model(name, pose, geometry, mu=DRY_MU, colour=EARTH):
    """One static model with matching collision and visual geometry."""
    x, y, z, roll, pitch, yaw = pose
    r, g, b = colour
    return f'''
    <model name="{name}">
      <static>true</static>
      <pose>{x:.4f} {y:.4f} {z:.4f} {roll:.4f} {pitch:.4f} {yaw:.4f}</pose>
      <link name="link">
        <collision name="collision">
          <geometry>{geometry}</geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry>{geometry}</geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material>
        </visual>
      </link>
    </model>'''


def box(sx, sy, sz):
    return f'<box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box>'


def ramp(name, x0, y, length, width, angle, mu=DRY_MU, up=True, base=0.0, colour=EARTH):
    """A ramp whose top surface runs from height base at x0 (up) or base + rise at x0 (down).

    A thick box tilted about y, sunk so only its top surface matters.
    @return The model and the x where the ramp ends
    """
    thickness = 0.3
    run = length * math.cos(angle)
    rise = length * math.sin(angle)
    # Centre of the top surface, then step half the thickness along the surface normal
    top_x, top_z = x0 + run / 2, base + rise / 2
    normal_x = -math.sin(angle) if up else math.sin(angle)
    normal_z = math.cos(angle)
    pitch = -angle if up else angle
    centre = (top_x - normal_x * thickness / 2, y, top_z - normal_z * thickness / 2, 0, pitch, 0)
    return model(name, centre, box(length, width, thickness), mu, colour), x0 + run


def plateau(name, x0, y, length, width, height, mu=DRY_MU, colour=EARTH):
    """A flat-topped block from the ground up to height."""
    return model(name, (x0 + length / 2, y, height / 2, 0, 0, 0), box(length, width, height), mu, colour)


def hill(prefix, x0, y, angle, ramp_length=0.8, top_length=0.6, width=1.0, mu=DRY_MU, colour=EARTH):
    """Up a ramp, across a flat top, down the other side."""
    rise = ramp_length * math.sin(angle)
    up, x1 = ramp(f'{prefix}_up', x0, y, ramp_length, width, angle, mu, up=True, colour=colour)
    top = plateau(f'{prefix}_top', x1, y, top_length, width, rise, mu, colour)
    down, _ = ramp(f'{prefix}_down', x1 + top_length, y, ramp_length, width, angle, mu, up=False, colour=colour)
    return up + top + down


def side_slope(name, y, angle, length=3.0, width=1.2, x0=-0.5):
    """A slope tilted about x, rising towards +y, centred on y with its middle at ground level + 0.2 m."""
    thickness = 0.3
    centre_height = 0.2
    pose = (x0 + length / 2,
            y + math.sin(angle) * thickness / 2,
            centre_height - math.cos(angle) * thickness / 2,
            angle, 0, 0)
    return model(name, pose, box(length, width, thickness))


def slopes_world():
    parts = []
    # Hills in lanes 1.5 m apart, each starting 0.5 m ahead of its spawn point (x = 0)
    for i, degrees in enumerate((5, 10, 15, 20)):
        parts.append(hill(f'hill_{degrees}', 0.5, i * 1.5, math.radians(degrees)))
    # Side slopes: the robot spawns on them and walks along x across the slope
    for i, degrees in enumerate((10, 15)):
        parts.append(side_slope(f'side_slope_{degrees}', -2.0 - i * 2.0, math.radians(degrees)))
    return HEADER.format(name='outdoor_slopes', mu=DRY_MU) + ''.join(parts) + FOOTER


def rocks_world(seed):
    rng = random.Random(seed)
    parts = []
    # Gentle bumps: big spheres sunk so 2-6 cm shows, like a lumpy field
    for i in range(14):
        radius = rng.uniform(0.8, 1.6)
        showing = rng.uniform(0.02, 0.06)
        x, y = rng.uniform(0.8, 4.5), rng.uniform(-1.5, 1.5)
        parts.append(model(f'bump_{i}', (x, y, showing - radius, 0, 0, 0),
                           f'<sphere><radius>{radius:.4f}</radius></sphere>'))
    # Rocks: tilted boxes, mostly 1-4 cm high with a few up to 7 cm (the feet lift 5 cm)
    for i in range(70):
        height = rng.uniform(0.04, 0.07) if rng.random() < 0.12 else rng.uniform(0.01, 0.04)
        sx, sy = rng.uniform(0.04, 0.14), rng.uniform(0.04, 0.14)
        x, y = rng.uniform(0.6, 4.5), rng.uniform(-1.5, 1.5)
        roll, pitch, yaw = rng.uniform(-0.25, 0.25), rng.uniform(-0.25, 0.25), rng.uniform(0, math.pi)
        # Half buried, so the top sits at about height, with the tilt adding a little more
        parts.append(model(f'rock_{i}', (x, y, 0.0, roll, pitch, yaw), box(sx, sy, 2 * height), colour=ROCK))
    return HEADER.format(name='outdoor_rocks', mu=DRY_MU) + ''.join(parts) + FOOTER


def low_friction_world():
    parts = []
    # Flat lanes 1.5 m apart, each a 3 m patch only 5 mm thick so it's no step
    lanes = (('dry', 1.0, EARTH), ('wet_grass', 0.6, (0.3, 0.5, 0.25)),
             ('mud', 0.4, (0.4, 0.3, 0.2)), ('wet_tile', 0.25, (0.6, 0.65, 0.7)))
    for i, (name, mu, colour) in enumerate(lanes):
        parts.append(model(f'patch_{name}', (1.0, i * 1.5, 0.0025, 0, 0, 0), box(3.4, 1.2, 0.005), mu, colour))
    # A 10 deg hill of mud
    parts.append(hill('mud_hill', 0.5, -1.5, math.radians(10), mu=0.4, colour=(0.4, 0.3, 0.2)))
    return HEADER.format(name='outdoor_low_friction', mu=DRY_MU) + ''.join(parts) + FOOTER


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--seed', type=int, default=7, help='rock field seed (default 7)')
    args = parser.parse_args()

    for name, content in (('outdoor_slopes', slopes_world()),
                          ('outdoor_rocks', rocks_world(args.seed)),
                          ('outdoor_low_friction', low_friction_world())):
        path = WORLDS_DIR / f'{name}.sdf'
        path.write_text(content)
        print(f'Wrote {path}')


if __name__ == '__main__':
    main()
